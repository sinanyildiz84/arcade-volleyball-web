#!/usr/bin/env python3
"""Generate the web port's sprite data and icons from the original Amiga source.

The Amiga sprites are pairs of 16x26 three-colour sprites; unlike the C64 port
(which has to shrink them to 24x21 hardware sprites) the browser can show them
at their original size, so this keeps all 32x26 pixels.

Usage: mkweb.py original/ArcadeVolleyball.c web/
"""
import re
import struct
import sys
import zlib

# SetRGB4 values from InitShapes(), scaled from 0-15 to 0-255
GREEN = ['#88ff88', '#66cc66', '#ccddcc']     # colours 21,22,23: left player
RED = ['#ff8888', '#cc6666', '#ddcccc']       # colours 25,26,27: right player
BALL = ['#cccccc', '#cccccc', '#cccccc']      # colours 29,30,31
NAMES = ['lmanOne', 'lmanTwo', 'lmanThree', 'rmanOne', 'rmanTwo', 'rmanThree',
         'ballOne', 'ballTwo', 'ballThree', 'ballFour']


def parse(path):
    src = open(path, encoding='latin-1').read()
    start = src.index('AVSpriteData[20][56]')
    body = src[start:src.index('};', start)]
    nums = [int(v, 16) for v in re.findall(r'0x([0-9A-Fa-f]{4})', body)]
    assert len(nums) == 20 * 56, len(nums)
    halves = []
    for s in range(20):
        w = nums[s * 56:(s + 1) * 56]
        rows = []
        for r in range(1, 27):          # skip the position/control words
            p0, p1 = w[r * 2], w[r * 2 + 1]
            rows.append([((p0 >> (15 - b)) & 1) | (((p1 >> (15 - b)) & 1) << 1)
                         for b in range(16)])
        halves.append(rows)
    # each object is a left and a right 16 pixel sprite side by side
    return [[halves[o * 2][r] + halves[o * 2 + 1][r] for r in range(26)] for o in range(10)]


def png(path, pixels, scale=1):
    h, w = len(pixels) * scale, len(pixels[0]) * scale
    raw = b''
    for row in pixels:
        line = b''.join(bytes(px) * scale for px in row)
        raw += (b'\0' + line) * scale

    def chunk(t, d):
        return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d))
    data = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0))
    data += chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b'')
    open(path, 'wb').write(data)


def rgba(hexcol, a=255):
    return (int(hexcol[1:3], 16), int(hexcol[3:5], 16), int(hexcol[5:7], 16), a)


def icon(objs, size):
    """The green player on a black rounded square, nearest-neighbour scaled."""
    man = objs[0]
    pal = [(0, 0, 0, 0)] + [rgba(c) for c in GREEN]
    sw, sh = 32, 26
    scale = max(1, int(size * 0.8) // sh)
    ox, oy = (size - sw * scale) // 2, (size - sh * scale) // 2
    out = [[(0, 0, 0, 255)] * size for _ in range(size)]
    r = size // 6                                   # rounded corners
    for y in range(size):
        for x in range(size):
            dx = min(x, size - 1 - x)
            dy = min(y, size - 1 - y)
            if dx < r and dy < r and (r - dx) ** 2 + (r - dy) ** 2 > r * r:
                out[y][x] = (0, 0, 0, 0)
    for y in range(sh):
        for x in range(sw):
            c = man[y][x]
            if not c:
                continue
            for yy in range(scale):
                for xx in range(scale):
                    py, px = oy + y * scale + yy, ox + x * scale + xx
                    if 0 <= py < size and 0 <= px < size:
                        out[py][px] = pal[c]
    return out


def main():
    src, out_dir = sys.argv[1], sys.argv[2].rstrip('/\\')
    objs = parse(src)
    with open(f'{out_dir}/sprites.js', 'w') as f:
        f.write('// Generated by tools/mkweb.py from the original Amiga sprite data.\n')
        f.write('// Ten 32x26 objects: three frames per player, four ball frames.\n')
        f.write('// Each row is one string, one character per pixel: 0 = transparent, 1-3 = colour.\n')
        f.write('// Plain globals, not a module, so the standalone single-file build works from file://.\n')
        f.write('const SPRITE_PALETTES = {\n')
        f.write(f'  green: {GREEN},\n  red: {RED},\n  ball: {BALL},\n'.replace("'", '"'))
        f.write('};\n\nconst SPRITES = {\n')
        for name, img in zip(NAMES, objs):
            rows = ',\n    '.join('"' + ''.join(str(c) for c in row) + '"' for row in img)
            f.write(f'  {name}: [\n    {rows},\n  ],\n')
        f.write('};\n')
    for size in (192, 512):
        png(f'{out_dir}/icon-{size}.png', icon(objs, size))
    print(f'{out_dir}/sprites.js: {len(objs)} objects, '
          f'{len(open(f"{out_dir}/sprites.js").read())} bytes; icons 192 and 512')


if __name__ == '__main__':
    main()
